//! **The cata liquid path's synthesised textures** — the wave normal map, the shoreline foam sheet,
//! the magma noise volume and the ripple perturbation kernel. No 1.12.1 install has any of them.
//!
//! `ProcWaterAbove`/`ProcWaterBelow` sample a per-liquid-type normal map on stage 5 four times per
//! fragment, at two tiling scales and two scroll phases, and blend the two pairs by view distance.
//! In the reference that texture is authored Cataclysm art, reached through
//! `Liquid::CMaterialSettings::GetTexture(mat, 2, 0)` — i.e. a `LiquidType.dbc` `Texture[]` column
//! that 1.12.1's `LiquidType.dbc` does not have. It is also not among the Cataclysm
//! client files this port was read from: its shader programs and `Ripples/perturbTex.blp`.
//!
//! So it is **synthesised**, not shipped: [`generate`] builds a tileable four-octave value-noise
//! height field and stores its central-difference normal. The bytes are generated once and
//! committed next to this file, then `include_bytes!`d — the binary answers for its own content
//! with no runtime cost and no dependency on a data directory, and benilla keeps its standing
//! promise to bundle no game assets (`README.md`), because nothing here came from Blizzard.
//!
//! The test below is the seam: it re-runs [`generate`] and compares against the committed bytes.
//! Change the algorithm and it fails until the blob is regenerated, which
//! `WOW_REGEN_LIQUID_ART=1 cargo test -p benilla-world liquid::art` does in place.
//!
//! The foam sheet ([`FOAM_SIZE`]) is the same story one stage further along: `ProcWaterAbove`'s
//! samp7, `GetTexture(mat, 3, 0)`, another `LiquidType.dbc` column 1.12.1 does not have. It is
//! generated by the same lattice, then ridged and sharpened into filaments — because the program
//! samples it twice and ADDS the two, so anything that is not foam has to be near-black or the
//! whole water surface lifts.
//!
//! The magma noise volume ([`NOISE_SIZE`]) stands in for `proceduralNoiseVolTex`, which the
//! reference builds from `XTextures\FX\noise.blob` — a megabyte of shipped data, and a file this
//! client has no copy of. `ProcMagma` reads its three channels as three independent masks, so this
//! generates three independent fields rather than one field in three channels: a grey volume would
//! composite all three lava layers on the same contour and the crust would move as one sheet.
//!
//! The ripple perturbation kernel is the one thing here that is NOT a texture, and the reason is
//! worth stating: the reference stamps `XTextures\Ripples\perturbTex.blp` for it, and that file
//! decodes (DXT1, 64², no alpha) to a plain radial falloff — 255 at the centre, 0 at the rim,
//! symmetric on both axes, profile `1.0, 0.976, 0.804, 0.514, 0.192, 0.031, 0.008, 0` at eighths of
//! the radius. That is a smoothstep applied twice, to within a couple of levels. Shipping a texture
//! of a function this file can write in one line would be dead weight, so `liquid_ripple.wgsl`
//! evaluates the curve instead and [`the_ripple_kernel_matches_the_reference_profile`] holds it to
//! the measured numbers.
//!
//! **Why a full RGBA normal and not a two-channel derivative.** The *below-water* program reads
//! three components off this texture (`ProcWaterBelow` perm 0: `add r1.xyz, r1, r2` … `dp3 r0.y,
//! r1, r1`), so the tap's `z` is load-bearing — a two-channel map would hand `normalize` a
//! zero-length vector the moment the camera goes under. `x`/`y`/`z` are stored `n · 0.5 + 0.5`, so
//! a flat texel is `(0.5, 0.5, 1.0)` and the programs' `tap_a + tap_b − 1` recovers a sum centred
//! on `+Z`.

use bevy::asset::RenderAssetUsages;
use bevy::image::{ImageAddressMode, ImageFilterMode, ImageSampler, ImageSamplerDescriptor};
use bevy::prelude::*;
use bevy::render::render_resource::{Extent3d, TextureDimension, TextureFormat};

/// Edge length of the bump map, in texels. Square and power-of-two: it is tiled at four different
/// scales at once, so a non-power-of-two period would beat against itself.
pub(super) const BUMP_SIZE: u32 = 256;

/// The committed bytes — `BUMP_SIZE² × RGBA8`, produced by [`generate`].
const BUMP_BYTES: &[u8] = include_bytes!("../../assets/liquid/water_bump.rgba");

/// Edge length of the shoreline foam sheet, in texels. Same size and the same reason as the bump
/// map: it is tiled, at two scales, and a non-power-of-two period would beat against itself.
pub(super) const FOAM_SIZE: u32 = 256;

/// The committed bytes — `FOAM_SIZE² × RGBA8`, produced by [`generate_foam`].
const FOAM_BYTES: &[u8] = include_bytes!("../../assets/liquid/water_foam.rgba");

/// Edge length of the magma noise volume's square face, in texels.
///
/// The reference's is 128². Halved here because the volume is *tiled* over the lava surface at two
/// scales and blended, so its own resolution is not what the eye reads — and because a 3D blob
/// costs its depth in repository bytes: 64² × 16 is a quarter megabyte, where 128² × 16 is a whole
/// one for detail that two overlapping samples immediately smear.
pub(super) const NOISE_SIZE: u32 = 64;

/// Slices through the magma noise volume — the reference's own 16.
///
/// This axis is TIME, not a third space dimension: the shader walks it with a clock, so the field
/// has to wrap on it like the other two or the lava would jump every sixteenth of a cycle.
pub(super) const NOISE_SLICES: u32 = 16;

/// The committed bytes — `NOISE_SIZE² × NOISE_SLICES × RGBA8`, produced by [`generate_noise`].
const NOISE_BYTES: &[u8] = include_bytes!("../../assets/liquid/magma_noise.rgba");

/// Build the `Image` the cata liquid materials bind on stage 5.
///
/// `RENDER_WORLD` only, like every other world texture: nothing on the CPU side reads it back, and
/// the main-world copy would be a quarter-megabyte held for nothing. The sampler repeats on both
/// axes — the whole point is tiling — and takes linear filtering.
pub(super) fn bump_image() -> Image {
    let mut image = Image::new(
        Extent3d {
            width: BUMP_SIZE,
            height: BUMP_SIZE,
            depth_or_array_layers: 1,
        },
        TextureDimension::D2,
        BUMP_BYTES.to_vec(),
        // NOT sRGB: this is a normal, not a colour. The gamma lane (`world_assets::images`) is
        // about colour bytes; pushing a direction through a transfer curve would bend it.
        TextureFormat::Rgba8Unorm,
        RenderAssetUsages::RENDER_WORLD,
    );
    image.sampler = ImageSampler::Descriptor(ImageSamplerDescriptor {
        label: Some("liquid_bump".into()),
        address_mode_u: ImageAddressMode::Repeat,
        address_mode_v: ImageAddressMode::Repeat,
        address_mode_w: ImageAddressMode::Repeat,
        mag_filter: ImageFilterMode::Linear,
        min_filter: ImageFilterMode::Linear,
        mipmap_filter: ImageFilterMode::Linear,
        ..default()
    });
    image
}

/// Build the `Image` the cata liquid materials bind on stage 7 — the shoreline foam sheet.
