    /// The volume's three channels are INDEPENDENT, and it wraps on the clock axis.
    ///
    /// Independence is the property `ProcMagma` actually depends on: the three are the masks for
    /// three separately composited lava layers, so a correlated volume would put every layer's
    /// edge on the same contour and the crust would breathe as one piece instead of churning.
    #[test]
    fn the_noise_volume_has_three_independent_channels_and_loops() {
        let (n, d) = (super::NOISE_SIZE as usize, super::NOISE_SLICES as usize);
        let b = super::NOISE_BYTES;
        assert_eq!(b.len(), n * n * d * 4);
        let at = |c: usize, x: usize, y: usize, z: usize| b[((z * n + y) * n + x) * 4 + c] as f32;
        // Pearson correlation between each pair of channels over one slice.
        for (a, c) in [(0usize, 1usize), (0, 2), (1, 2)] {
            let pts: Vec<(f32, f32)> = (0..n * n)
                .map(|i| (at(a, i % n, i / n, 0), at(c, i % n, i / n, 0)))
                .collect();
            let m = |f: fn(&(f32, f32)) -> f32| pts.iter().map(f).sum::<f32>() / pts.len() as f32;
            let (ma, mc) = (m(|p| p.0), m(|p| p.1));
            let cov: f32 = pts.iter().map(|p| (p.0 - ma) * (p.1 - mc)).sum();
            let va: f32 = pts.iter().map(|p| (p.0 - ma).powi(2)).sum::<f32>().sqrt();
            let vc: f32 = pts.iter().map(|p| (p.1 - mc).powi(2)).sum::<f32>().sqrt();
            let r = cov / (va * vc).max(1e-6);
            assert!(
                r.abs() < 0.2,
                "channels {a}/{c} correlate at {r} - not independent masks"
            );
        }
        // The clock axis wraps: the last slice continues into the first.
        for (x, y) in [(3usize, 7usize), (31, 31), (60, 12)] {
            let step = (at(0, x, y, 1) - at(0, x, y, 0)).abs();
            let seam = (at(0, x, y, 0) - at(0, x, y, d - 1)).abs();
            assert!(
                seam <= step * 3.0 + 8.0,
                "clock seam at ({x},{y}): {seam} vs step {step}"
            );
        }
    }

    /// The ripple kernel `liquid_ripple.wgsl` evaluates IS the reference's `perturbTex.blp`.
    ///
    /// The shader stamps a disturbance with `smoothstep(smoothstep(1 − r))` rather than sampling a
    /// texture. This is the evidence for that substitution: the numbers below were decoded straight
    /// out of the Cataclysm client's `XTextures/Ripples/perturbTex.blp` (DXT1, 64 × 64, mid-row, one sample
    /// every four texels out from the centre), and the curve has to pass through them.
    ///
    /// The tolerance is a fit's, not a reproduction's — what it pins is that the shape stays a
    /// smooth radial falloff and does not drift into a cone, a step or a disc.
    #[test]
    fn the_ripple_kernel_matches_the_reference_profile() {
        // `liquid_ripple.wgsl`'s `kernel`, in Rust.
        fn kernel(r: f32) -> f32 {
            let t = (1.0 - r).clamp(0.0, 1.0);
            let a = super::smoothstep(t);
            super::smoothstep(a)
        }
        // perturbTex.blp's mid row at r = 0, 4, 8 … 28 texels from a 32-texel centre.
        let reference = [255.0, 252.0, 249.0, 205.0, 131.0, 49.0, 8.0, 2.0];
        for (i, want) in reference.iter().enumerate() {
            let r = (i * 4) as f32 / 32.0;
            let got = kernel(r) * 255.0;
            assert!(
                (got - want).abs() < 48.0,
                "kernel at r={r} is {got}, perturbTex.blp has {want}"
            );
        }
        assert_eq!(kernel(1.0), 0.0, "the kernel must be hard zero at the rim");
        assert_eq!(kernel(0.0), 1.0, "the kernel must reach full at the centre");
    }

    /// The encoded field is unit normals with a positive `z`, and it TILES.
    ///
    /// The second half is the property the four-tap blend actually depends on: a seam would read as
    /// a hard line swimming across the water at four different scales at once.
    #[test]
    fn the_bump_map_is_unit_normals_and_wraps() {
        let n = super::BUMP_SIZE as usize;
        let b = super::BUMP_BYTES;
        let nrm = |x: usize, y: usize| {
            let i = (y * n + x) * 4;
            let d = |c: usize| b[i + c] as f32 / 255.0 * 2.0 - 1.0;
            (d(0), d(1), d(2))
        };
        for (x, y) in [(0usize, 0usize), (7, 91), (128, 128), (255, 255)] {
            let (a, c, e) = nrm(x, y);
            let len = (a * a + c * c + e * e).sqrt();
            assert!((len - 1.0).abs() < 0.02, "({x},{y}) is not unit: {len}");
            assert!(e > 0.0, "({x},{y}) points into the surface");
        }
        // Column 0 continues column 255, and row 0 continues row 255 — within a slope step of what
        // the interior gradient does, not exactly equal (they are different texels).
        for i in 0..n {
            let (l, r) = (nrm(0, i), nrm(n - 1, i));
            let (t, bo) = (nrm(i, 0), nrm(i, n - 1));
            assert!((l.0 - r.0).abs() < 0.35, "vertical seam at row {i}");
            assert!((t.1 - bo.1).abs() < 0.35, "horizontal seam at column {i}");
        }
    }
