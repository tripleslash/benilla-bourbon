/// Where the page remembers the flavor of the last realm played, so the next boot can put that
/// flavor's character screens on disk before the realm is even chosen. A hint and nothing more:
/// the client mounts the Turtle layer off the realm list, never off this.
const FLAVOR_KEY = 'wenilla.flavor';

function rememberFlavor(flavor) {
  safeLocalSet(FLAVOR_KEY, flavor);
}

/// A container manifest's glue set, offset into the layer's key space (`benilla-pack sidecars`,
/// `web/glue-manifest.json`): its glue-screen art and every character model and texture it holds.
function layerGlue(manifest, layer = { keyBase: 0 }) {
  const glue = (manifest && manifest.glue) || { packs: [] };
  return glue.packs.map(([id, bytes]) => [id + layer.keyBase, bytes]);
}

/// Every glue set this boot puts on disk: the corpus's, the open HD layer's, and the remembered
/// flavor's (`flavorGlue`).
async function glueSets(opts) {
  if (opts.glue === false) return [];
  const sets = [...layerGlue(packs.manifest)];
  if (packs.hdIndex) sets.push(...layerGlue(packs.hdManifest, LAYERS.hd));
  sets.push(...(await flavorGlue()));
  return sets;
}

/// A returning Turtle WoW player's layer packs: its boot set and its glue set, and the reforged
/// art's with that setting on — fetched onto disk only. The layers are not opened here; the client
/// still mounts them on entering the realm, and then reads all of this locally.
async function flavorGlue() {
  if (safeLocalGet(FLAVOR_KEY) !== 'turtle') return [];
  const out = [];
  const wanted = reforgedWanted() ? ['turtle', 'reforged'] : ['turtle'];
  for (const name of wanted) {
    const layer = LAYERS[name];
    const manifest = await fetchJson(`${location.origin}/${layer.segment}/boot-packs.json`);
    if (!manifest) continue;
    const boot = (manifest.boot && manifest.boot.packs) || [];
    out.push(...boot.map(([id, bytes]) => [id + layer.keyBase, bytes]), ...layerGlue(manifest, layer));
  }
  return out;
}

/// Put packs on disk without decoding them into the resident map: the glue sets run to hundreds
/// of megabytes, and the resident map is a 256 MB working set that would evict the boot packs to
/// hold them. A read of one of these later is a local answer — `sw.js` serves the synchronous lane
/// from the same store — instead of a round trip.
///
/// A pack already on disk costs one `match` and no body read, so a repeat visit walks this list
/// at cache-lookup speed. With no service worker in control, `fetchWire` writes the page's own
/// Cache Storage instead, which is the whole persistence such a page has.
async function persistPacks(list, onProgress) {
  const total = list.reduce((n, [, bytes]) => n + bytes, 0);
  if (!list.length) return onProgress(0, total);
  let cache = null;
  if (packs.sw) {
    try {
      cache = await caches.open(SW_CACHE);
    } catch (_) {
      cache = null;
    }
  }
  let done = 0;
  const queue = list.slice();
  const worker = async () => {
    for (;;) {
      const job = queue.shift();
      if (job === undefined) return;
      const [id, bytes] = job;
      const url = packs.url(id);
      try {
        if (cache) {
          if (!(await cache.match(new URL(url).pathname))) {
            // Through the worker, which stores it; the body is drained so the store completes.
            const r = await fetchRetry(url);
            if (r.ok) await r.arrayBuffer();
          }
        } else if (!packs._resident.has(id)) {
          await packs.fetchWire(id, url);
        }
      } catch (_) {
        /* a miss here is a slower read later, never a failure */
      }
      done += bytes;
      onProgress(done, total);
    }
  };
  onProgress(0, total);
  await Promise.all(Array.from({ length: PREFETCH_CONCURRENCY }, worker));
}

/// The world-entry pack set, warmed after the client reports `ready` (see boot.js). Same shape as
/// the boot set and deliberately separate: it is what the first in-game draw resolves, and it is
/// warmed while the player is still at the glue screens.
export async function prefetchWorld(onProgress = () => {}) {
  const world = (packs.manifest && packs.manifest.world) || { packs: [], bytes: 0 };
  await prefetch(world.packs, onProgress);
}

// ---- the service worker ------------------------------------------------------------------

/// Root-scoped so it can see `/data/*` from any page that hosts the client — `web/index.html` at
/// `/`, and any hosting page that boots the client from a subpath.
const SW_URL = '/sw.js';
/// The worker's one cache, keyed by pathname. Twin of `sw.js`'s `CACHE`.
const SW_CACHE = 'wenilla-data';
/// How long to wait for a first-visit worker to claim this page. It is `clients.claim()` in an
/// `activate` handler, so this is milliseconds in practice; the bound exists so a worker that
/// somehow never activates costs a delay instead of a boot.
const SW_CLAIM_TIMEOUT_MS = 5000;
/// Likewise for the build handshake: a worker that does not answer is one the page proceeds
/// without, on the pre-worker path's terms.
const SW_MESSAGE_TIMEOUT_MS = 5000;

/// Install `sw.js` and report whether it is actually CONTROLLING this page — which is the only
/// state that matters, since a registered-but-not-controlling worker sees none of our fetches and
/// pinning the policy for it would be a lie.
async function registerWorker(enabled) {
  if (!enabled) {
    await unregisterWorker();
    // Unregistering does NOT un-control the page that is already loaded: a worker installed on an
    // earlier visit keeps serving this document's fetches until it navigates. So `?nosw=1` takes
    // full effect on the NEXT load, and reporting the truth here — rather than a flat `false` — is
    // what stops this load from opening a second cache beside the one still answering it.
    return !!(navigator.serviceWorker && navigator.serviceWorker.controller);
  }
  // `isSecureContext` rather than a protocol test: `http://127.0.0.1` is secure and is how
  // `wenilla-host` is run, while `http://` to a LAN address is not and has no service workers at
  // all. The page must still boot there, on the pre-worker path.
  if (!('serviceWorker' in navigator) || !self.isSecureContext) return false;
  try {
    await navigator.serviceWorker.register(SW_URL, { scope: '/' });
  } catch (e) {
    console.warn('wenilla: service worker registration failed —', e);
    return false;
  }
  if (navigator.serviceWorker.controller) return true;
  return await new Promise((resolve) => {
    const finish = (controlled) => {
      clearTimeout(timer);
      navigator.serviceWorker.removeEventListener('controllerchange', onChange);
      resolve(controlled);
    };
    const onChange = () => finish(!!navigator.serviceWorker.controller);
    const timer = setTimeout(() => finish(false), SW_CLAIM_TIMEOUT_MS);
    navigator.serviceWorker.addEventListener('controllerchange', onChange);
  });
}

async function unregisterWorker() {
  if (!('serviceWorker' in navigator)) return;
  try {
    const registrations = await navigator.serviceWorker.getRegistrations();
    await Promise.all(registrations.map((r) => r.unregister()));
  } catch (_) {
    /* nothing to undo */
  }
}

/// Tell the worker which container this is, and wait for it to say it has reconciled — see
/// `sw.js`'s `syncBuild`. Resolves to `{ok, purged}`, or `null` when there is no worker to ask or
/// it did not answer in time.
///
/// Awaited rather than fired and forgotten: the answer gates the first cache-first read, and a page
/// that raced ahead could be handed an index from a container the origin no longer serves.
function syncBuild(buildId) {
  const worker = navigator.serviceWorker && navigator.serviceWorker.controller;
  if (!worker || !buildId) return Promise.resolve(null);
  return new Promise((resolve) => {
    const channel = new MessageChannel();
    const timer = setTimeout(() => resolve(null), SW_MESSAGE_TIMEOUT_MS);
    channel.port1.onmessage = (e) => {
      clearTimeout(timer);
      resolve(e.data || null);
    };
    try {
      worker.postMessage({ type: 'wenilla-build', buildId }, [channel.port2]);
    } catch (_) {
      clearTimeout(timer);
      resolve(null);
    }
  });
}

// ---- the decode worker -------------------------------------------------------------------

/// Start `packworker.js` and open the container inside it. Resolves to the worker, or to `null`
/// for every way it can fail to be useful — no `Worker` constructor, a script that will not load, a
/// wasm that will not instantiate, an index it cannot parse, or a silence longer than
/// [`WORKER_OPEN_TIMEOUT_MS`]. Nothing downstream branches on *why*.
///
/// The build-id check at the end is the one hard refusal. Everything else degrades to slower; a
/// worker decoding against a different container's index would hand back plausible bytes from the
/// wrong offsets, which is the failure mode nothing downstream could detect.
async function startWorker(enabled) {
  if (!enabled || typeof Worker === 'undefined' || !packs.index) return null;
  let worker;
  try {
    worker = new Worker(WORKER_URL);
  } catch (e) {
    console.warn('wenilla: pack worker failed to start —', e);
    return null;
  }
  let finishOpen = () => {};
  const opened = new Promise((resolve) => {
    const onMessage = (e) => {
      const m = e.data;
      // `!m.layer` — a layer opens through its own handshake (`openLayerInWorker`) and its reply
      // must not settle this one. They cannot overlap today (a layer is opened after this returns),
      // but a handshake that reads any reply is a handshake that breaks the first time one does.
      if (m && !m.layer && (m.type === 'opened' || m.type === 'failed')) finishOpen(m);
    };
    const timer = setTimeout(() => finishOpen(null), WORKER_OPEN_TIMEOUT_MS);
    finishOpen = (answer) => {
      clearTimeout(timer);
      worker.removeEventListener('message', onMessage);
      resolve(answer);
    };
    worker.addEventListener('message', onMessage);
  });

  // Registered before the first message, and it ends the handshake as well as reporting: a worker
  // that throws while loading its own script never answers, and without this the boot would sit on
  // the ten-second timeout to learn what this already knows.
  worker.onerror = (e) => {
    console.warn('wenilla: pack worker error —', (e && e.message) || e);
    finishOpen(null);
    dropWorker('the pack worker failed');
  };

  // A COPY of the index, transferred. The page keeps its own — `Chain::open` reads it out of
  // `packs.index` — and 1.6 MB duplicated once at boot is the price of the worker knowing each
  // pack's codec and decoded size, which are index fields a `.bpk` does not restate.
  const copy = packs.index.slice().buffer;
  worker.postMessage({ type: 'open', base: packs.base, index: copy }, [copy]);

  const answer = await opened;
  if (!answer || answer.type !== 'opened') {
    console.warn('wenilla: pack worker did not open the container —', (answer && answer.error) || 'no answer');
    worker.terminate();
    return null;
  }
  if (packs.buildId && answer.buildId !== packs.buildId) {
    console.warn(
      `wenilla: pack worker opened container ${answer.buildId}, page has ${packs.buildId} — not using it`
    );
    worker.terminate();
    return null;
  }
  worker.addEventListener('message', onWorkerMessage);
  packs.worker = worker;
  // Only with `sw.js` in control does the worker fetch for itself; otherwise Cache Storage lives
  // here and so does the fetch. See `packworker.js`'s header.
  packs._workerFetches = packs.sw;
  return worker;
}

/// The worker's answers. A `body` is adopted straight into the resident map — `m.body` is a
/// transferred `ArrayBuffer`, so this is a view over bytes that were never copied on this thread.
function onWorkerMessage(e) {
  const m = e.data;
  if (!m) return;
  if (m.type === 'body') {
    packs.put(m.id, new Uint8Array(m.body));
    packs._settle(m.id, true);
  } else if (m.type === 'miss') {
    packs._settle(m.id, false, m.error);
  }
}

/// Lose the worker and settle everything waiting on it as "not resident", so a warm in flight when
/// it died becomes a slow read rather than a promise nobody ever resolves.
function dropWorker(reason) {
  const worker = packs.worker;
  packs.worker = null;
  if (worker) worker.terminate();
  for (const id of Array.from(packs._pending.keys())) packs._settle(id, false, reason);
}

/// Ask the browser to exempt this origin's storage from eviction.
///
/// A "no" is not a failure — every path through this file and `sw.js` is correct against an empty
/// cache — but the ask is worth making, because without a grant the corpus is merely "best-effort"
/// storage the browser may evict under disk pressure, and re-downloading 3.3 GiB is the exact cost
/// all of this exists to remove. Chrome grants it silently on an engaged origin; Firefox prompts,
/// which is why the caller does not await this.
///
/// `persisted()` first so an origin that already has the grant never re-prompts.
async function requestPersistence() {
  if (!navigator.storage || !navigator.storage.persist) return false;
  try {
    if (navigator.storage.persisted && (await navigator.storage.persisted())) return true;
    return await navigator.storage.persist();
  } catch (_) {
    return false;
  }
}

/// One `Range: bytes=0-15` against a real pack. 206 with exactly 16 bytes back is the only proof
/// that counts; anything else means whole-object fetches, which are never wrong, only bigger.
async function probe(url) {
  try {
    const r = await fetch(url, { headers: { Range: 'bytes=0-15' } });
    const body = await r.arrayBuffer();
    packs.policy = r.status === 206 && body.byteLength === 16 ? 'range' : 'whole';
  } catch (_) {
    packs.policy = 'whole';
  }
  safeLocalSet(POLICY_KEY, packs.policy);
}

/// Warm a list of `[packId, wireBytes]` (plus any extra URLs) through a fixed-size pool, reporting
/// bytes rather than files — an object is ~0.6 MB, so "12 of 31" says much less than "8 of 19 MB".
///
/// Failures are counted as done and otherwise ignored: a miss means that pack loads the slow way,
/// which is exactly the behaviour of a page that never prefetched at all.
async function prefetch(list, onProgress, extraUrls = []) {
  const jobs = list.map(([id, bytes]) => ({ id, bytes, url: packs.url(id) }));
  for (const url of extraUrls) jobs.push({ id: null, bytes: 0, url });
  const total = jobs.reduce((n, j) => n + j.bytes, 0);
  if (!jobs.length) return onProgress(0, 0);
  let done = 0;
  onProgress(0, total);
  const queue = jobs.slice();
  const worker = async () => {
    for (;;) {
      const job = queue.shift();
      if (job === undefined) return;
      try {
        if (job.id === null) {
          // The listfile rides along: it is the one side file the client fetches lazily, and
          // fetching it here means `Chain::list` never blocks on it.
          const r = await fetchRetry(job.url);
          if (r.ok) packs.listfile = await r.text();
        } else if (packs.worker) {
          // Through the worker, so the pack lands DECODED in the resident map and the first read
          // of anything in it is a memcpy. `false` back means it could not be warmed that way;
          // a prefetch miss is already a non-event (the read path re-fetches), so it is not
          // retried here — retrying would only pay for the same failure twice before boot.
          await packs.warmPack(job.id, job.url);
        } else {
          await packs.fetchWire(job.id, job.url);
        }
      } catch (_) {
        /* offline blip, 404 drift — the read path deals with it */
      }
      done += job.bytes;
      onProgress(done, total);
    }
  };
  await Promise.all(Array.from({ length: PREFETCH_CONCURRENCY }, worker));
}

/// `index.bpi`'s build id: the u64 at offset 48, as hex. Read here rather than passed down from
/// Rust because Cache Storage has to be namespaced before the first pack is fetched, which is
/// before the wasm module exists.
function readBuildId(bytes) {
  const view = new DataView(bytes.buffer, bytes.byteOffset, bytes.byteLength);
  const lo = view.getUint32(48, true);
  const hi = view.getUint32(52, true);
  return hi.toString(16).padStart(8, '0') + lo.toString(16).padStart(8, '0');
}

async function fetchJson(url) {
  try {
    const r = await fetch(url);
    return r.ok ? await r.json() : null;
  } catch (_) {
    return null;
  }
}

// localStorage throws outright in some privacy configurations rather than merely being empty.
function safeLocalGet(key) {
  try {
    return localStorage.getItem(key);
  } catch (_) {
    return null;
  }
}

function safeLocalSet(key, value) {
  try {
    localStorage.setItem(key, value);
  } catch (_) {
    /* nothing to do; the probe just runs again next visit */
  }
}

// ---- transient-failure retry -------------------------------------------------------------
//
// Three copies of this live in the tree — here, `packworker.js` and `sw.js` — because the three
// run in different worlds: this is an ES module, the pack worker is `importScripts`, and the
// service worker is a classic worker with no module graph at all. A shared file would have to be
// authored for all three loaders at once, which is more machinery than fifty lines deserve. They
// are kept identical on purpose; change one, change all three.
/// How many times a transient failure is re-tried before the caller is told it failed. Four
/// attempts total, so the worst case adds ~1.4 s of backoff before giving up.
const RETRY_ATTEMPTS = 4;
/// First backoff, doubled per attempt: 150, 300, 600 ms, plus jitter.
const RETRY_BASE_MS = 150;
/// The statuses worth asking again for. **429 is the one this exists for** — A static host rate-limits
/// a burst of object requests, and the boot prefetch is exactly a burst of object requests — with
/// the 5xx family alongside it because an edge under load answers those the same way, transiently.
///
/// **404 is deliberately absent, and so is every other 4xx.** A missing pack is a fact about the
/// hosted tree, not a hiccup: `Chain::read` turns it into the correct "file not in patch chain",
/// and retrying it three times would turn one honest error into four and delay it by a second.
const RETRY_STATUS = new Set([408, 425, 429, 500, 502, 503, 504]);

/// `fetch` with backoff on the failures a static object store actually produces under load.
///
/// The corpus is a few thousand objects fetched six-wide at boot and again at every zone edge, so
/// "the origin said 429 once" is a normal event in a normal session, not an outage. Before this,
/// one of those became a pack the resident map never got: the read path fell back to a blocking
/// XHR, or the prefetch simply dropped it and the first frame that wanted it paid a round trip —
/// and on a genuinely rate-limited burst, dozens did at once.
///
/// `Retry-After` is honoured when the origin sends one (seconds, or an HTTP date), because an
/// origin that tells you when to come back knows better than the schedule below. It is clamped, so
/// a header saying "an hour" costs one attempt rather than hanging the boot.
///
/// Jittered, because the whole point is that six workers hit the limit at the same instant; a fixed
/// backoff would have all six come back at the same instant too.
export async function fetchRetry(url, init, attempts = RETRY_ATTEMPTS) {
  let lastErr;
  for (let attempt = 0; attempt < attempts; attempt += 1) {
    let response;
    try {
      response = await fetch(url, init);
    } catch (e) {
      // A rejected fetch is a network-layer failure (offline, DNS, a dropped connection). Those are
      // exactly the transient class, so they retry — but the last one is re-thrown, not swallowed,
      // because a caller that asked for bytes must not be handed `undefined`.
      lastErr = e;
      if (attempt + 1 >= attempts) throw e;
      await sleep(retryDelayMs(attempt, null));
      continue;
    }
    if (!RETRY_STATUS.has(response.status) || attempt + 1 >= attempts) return response;
    await sleep(retryDelayMs(attempt, response.headers.get('Retry-After')));
  }
  // Unreachable: the loop either returns a response or throws on its last attempt.
  throw lastErr || new Error(`fetch(${url}) exhausted ${attempts} attempts`);
}

/// The wait before attempt `n + 1` — `Retry-After` when the origin sent a usable one, else
/// exponential backoff with up to 50% jitter. Capped at 5 s so a hostile header cannot stall a boot.
function retryDelayMs(attempt, retryAfter) {
  const capped = (ms) => Math.max(0, Math.min(5000, ms));
  if (retryAfter) {
    const secs = Number(retryAfter);
    if (Number.isFinite(secs)) return capped(secs * 1000);
    const when = Date.parse(retryAfter);
    if (Number.isFinite(when)) return capped(when - Date.now());
  }
  const base = RETRY_BASE_MS * 2 ** attempt;
  return capped(base + Math.random() * base * 0.5);
}

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
