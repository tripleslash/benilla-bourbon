// packs.js — the page's half of the BENPACK container the client streams its game data from.
//
// The client no longer asks a companion host for one game file at a time; it reads ~4,700 static
// objects (`data/p/<hi>/<id>.bpk`) plus one index (`data/index.bpi`) off whatever dumb object store
// serves this page. Rust does the resolution and the decoding (`benilla_formats::webpack`); this
// file owns the four things that belong on the JS side of that line:
//
//   1. THE RESIDENT MAP. Decoded pack bodies live here, in a JS `Map`, NOT in wasm linear memory.
//      The corpus is 3.3 GiB served; wasm's address space is 4 GiB and only ever grows — a Vec that
//      Rust frees goes back to Rust's allocator, never to the browser. Here the same bytes are
//      ordinary garbage, and eviction is a budget in bytes rather than a data-structure change.
//   2. THE RANGE PROBE. A CDN edge slices ranges only for objects it has stored, and its
//      default `max-age=0, must-revalidate` means it never stores one — measured: `Range:
//      bytes=100-199` comes back 200 with the whole body. So support is measured, not assumed, and
//      re-measured after the boot prefetch (see reprobe): "the edge has now stored these objects"
//      is exactly the state where 206s start appearing.
//   3. PERSISTENCE, which is now `sw.js`'s job and this file's to hand over — see below.
//   4. THE BOOT PREFETCH. `boot-packs.json` names the packs a boot and a world entry actually
//      touch, generated by the packer from the checked-in read-set manifests. It now warms them
//      through `packworker.js`, so a prefetched pack arrives DECODED — see below.
//
// ## Persistence moved to a service worker, and what that changes here
//
// This file used to own Cache Storage directly, and it could only ever close half the problem: the
// cache is async-only, so the ~60 synchronous `Chain::read` call sites — a blocking XHR, which
// cannot await a Promise — could not read it and fell back to the HTTP cache, a store the browser
// evicts and revalidates on its own schedule. `sw.js` sits below that distinction and answers both
// lanes from one permanent store, so the rules here are now:
//
// - **Persistence is the worker's, not ours.** With a controller in place `_openCache` stays shut
//   and every fetch below goes through the worker, which caches it. Two copies of a 3.3 GiB corpus
//   against one quota is not a redundancy worth having, and the worker's copy is the one the
//   synchronous lane can also see. The direct path stays for a page with no worker (an insecure
//   origin, a browser that refuses one), where it is still the whole cache there is.
// - **The range policy is pinned to `whole`.** Not because ranges stopped working — the worker
//   answers them locally and would answer every one — but because with the object already on disk
//   `whole` strictly dominates: it costs the same nothing, and it puts the DECODED body in the
//   resident map, after which every later read in that locality group is a memcpy instead of a
//   round trip through the worker. Ranges exist to avoid over-fetching from a Range-less origin,
//   and once the over-fetch is paid once, forever, there is nothing left for them to save. Both
//   probes are skipped with it, which also takes two round trips out of boot.
//
// `?nosw=1` turns all of that off and unregisters the worker, which is how the pre-worker path —
// and `wenilla-host --no-ranges`, the Range-less emulation the fallback exists for — stays
// exercisable.
//
// ## The decode worker (`web/packworker.js`)
//
// Warming a pack used to mean putting its WIRE bytes somewhere — the service worker's cache — and
// leaving the decode to the first read that wanted it, which ran in Rust, in the first update's
// catalog task, on the thread that draws. `warmPack` closes that: `packworker.js` fetches and
// decodes off-thread and posts the body back as a transferable `ArrayBuffer`, which lands in the
// resident map below at zero copy. A prefetched pack is therefore *decoded and resident* before
// `init()`, and the ~60 synchronous `Chain::read` sites that follow are memcpys.
//
// It is an accelerator, never a dependency. No `Worker`, a wasm that will not load, a worker that
// dies mid-session: every pending warm settles as "not resident" and the read path does exactly
// what it did before. `?noworker=1` forces that state for bisecting.
//
// Page contract: a plain global, `window.__wenilla_packs`, like every other seam this client uses
// (`__wenilla_env`, `__wenilla_progress`, `__wenilla_boottrace`). Deliberately not a wasm-bindgen
// module import: the client must still run on a page that ships none of this — the resident map is
// then always empty, every read re-fetches its pack, and `wenilla-host --www web/dist` stays a
// usable way to bisect a rendering bug.

/// Resident budget. Packs are ~0.6 MB decoded at the container's measured p50, so this is a few
/// hundred of them — comfortably the whole boot set plus a zone's worth of terrain.
const RESIDENT_BUDGET_BYTES = 256 * 1024 * 1024;
/// Fetch pool width for the prefetch. Matches boot.js's old per-name pool; the objects are ~50x
/// larger now, so this is bandwidth-bound rather than round-trip-bound and the number matters less.
const PREFETCH_CONCURRENCY = 6;
/// How many warms may be in flight at once — and, therefore, the reason `_warmQueue` exists at all.
///
/// Before this there was no queue: every `warmPack` posted to the worker (or started a fetch) the
/// instant it was asked for, and the ORDER packs arrived in was whatever order the browser's own
/// six-connections-per-host limit happened to drain. That is fine when every pack is equally
/// wanted. It is not fine at a zone boundary, where a few hundred texture warms are asked for in
/// the same frame as the one `.adt` and the three `.wmo` groups that decide whether there is a
/// floor under the player — those four then queue behind the art, arrive seconds late, and the
/// body walks onto ground that has no collider yet.
///
/// Six matches what the browser would have allowed anyway, so throughput is unchanged; what
/// changes is that WE choose which six, by `priority` (see `warmPack`).
const WARM_CONCURRENCY = 6;
/// Warm priority: **collision-bearing reads** — terrain tiles and the layer art that completes
/// them, WMO roots and groups, M2 headers (their bounds and collision hulls) — go ahead of
/// everything else, and terrain near the player goes ahead of the rest of that. The classifier is
/// Rust's (`benilla_formats::web::warm_priority`), which is where the name law already lives; this
/// file only orders what it is told, and `benilla-formats`' `web_names` test pins the five numbers
/// below against their Rust twins.
///
/// The tile under the view focus, the one neighbouring tile the body is nearest to stepping onto,
/// and the map's WDT.
const PRIORITY_TERRAIN_FOCUS = 0;
/// The rest of the focus tile's 8 neighbours.
const PRIORITY_TERRAIN_NEAR = 1;
/// Terrain further out, the WDL horizon, and `Tileset\` layer art.
const PRIORITY_TERRAIN = 2;
/// Collision-bearing model art: `.wmo` roots and groups, `.m2`/`.mdx`. **The bottom of the
/// collision lane** — the reservation below spans `priority <= PRIORITY_GEOMETRY`, so every terrain
/// tier is inside it and the test stays one comparison.
const PRIORITY_GEOMETRY = 3;
/// Everything else: textures, sounds, DBCs, UI art. The default when a caller names no priority.
const PRIORITY_NORMAL = 4;
/// How many of `WARM_CONCURRENCY`'s slots the collision lane may hold **while anything else is
/// waiting**.
///
/// Strict priority is not a queue discipline, it is a starvation policy, and this queue has a
/// caller that cannot survive one. A UI sprite read answers `Pending` while its pack is missing and
/// the FrameXML extract gate re-runs a full conversion on every deferral — so art that never
/// arrives is not "art that never arrives", it is a full UI rebuild every frame for as long as the
/// geometry queue is non-empty. Running across a zone keeps it non-empty indefinitely.
///
/// So the collision lane gets a big majority and never the whole pool: four of six while art is
/// queued, all six when it is not. The reservation costs a third of the bandwidth in exactly the
/// moments there is a backlog, and buys the guarantee that every lane keeps moving.
const WARM_GEOMETRY_SLOTS = 4;
/// Stop writing Cache Storage at this fraction of the origin's quota. Going over does not fail
/// loudly — the browser evicts something, possibly the packs we just wrote — so leaving headroom is
/// how the cache stays useful rather than thrashing.
const QUOTA_CEILING = 0.8;
/// Where the probe result is remembered per origin, so a repeat visit starts with the right policy
/// instead of paying a demotion to learn it again.
const POLICY_KEY = 'wenilla-range-policy';
