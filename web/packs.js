/// `p/<hi>/<id>.bpk` — the twin of `benilla_pack::pack_path`. The index carries no path table (the
/// path IS the id), so this law exists in exactly two places and they must agree; the container's
/// own `pack_id` header field is what catches it if they ever stop agreeing.
function packPath(id) {
  const hi = ((id >> 8) & 0xff).toString(16).padStart(2, '0');
  return `p/${hi}/${id.toString(16).padStart(4, '0')}.bpk`;
}

