// packs.js — the page's half of the BENPACK container the client streams its game data from.
//
// The client no longer asks a companion host for one game file at a time; it reads ~4,700 static
// objects (`data/p/<hi>/<id>.bpk`) plus one index (`data/index.bpi`) off whatever dumb object store
// serves this page. Rust does the resolution and the decoding (`benilla_formats::webpack`); this
// file owns the four things that belong on the JS side of that line:
//
//   1. THE RESIDENT MAP. Decoded pack bodies live here, in a JS `Map`, NOT in wasm linear memory.
//      The corpus is 3.3 GiB served; wasm's address space is 4 GiB and only ever grows — a Vec that
//      Rust frees goes back to Rust's allocator, never to the browser. Here the same bytes are
//      ordinary garbage, and eviction is a budget in bytes rather than a data-structure change.
//   2. THE RANGE PROBE. the host's edge slices ranges only for objects it has stored, and its
//      default `max-age=0, must-revalidate` means it never stores one — measured: `Range:
//      bytes=100-199` comes back 200 with the whole body. So support is measured, not assumed, and
//      re-measured after the boot prefetch (see reprobe): "the edge has now stored these objects"
//      is exactly the state where 206s start appearing.
//   3. PERSISTENCE, which is now `sw.js`'s job and this file's to hand over — see below.
//   4. THE BOOT PREFETCH. `boot-packs.json` names the packs a boot and a world entry actually
//      touch, generated by the packer from the checked-in read-set manifests. It now warms them
//      through `packworker.js`, so a prefetched pack arrives DECODED — see below.
//
// ## Persistence moved to a service worker, and what that changes here
//
// This file used to own Cache Storage directly, and it could only ever close half the problem: the
// cache is async-only, so the ~60 synchronous `Chain::read` call sites — a blocking XHR, which
// cannot await a Promise — could not read it and fell back to the HTTP cache, a store the browser
// evicts and revalidates on its own schedule. `sw.js` sits below that distinction and answers both
// lanes from one permanent store, so the rules here are now:
//
// - **Persistence is the worker's, not ours.** With a controller in place `_openCache` stays shut
//   and every fetch below goes through the worker, which caches it. Two copies of a 3.3 GiB corpus
//   against one quota is not a redundancy worth having, and the worker's copy is the one the
//   synchronous lane can also see. The direct path stays for a page with no worker (an insecure
//   origin, a browser that refuses one), where it is still the whole cache there is.
// - **The range policy is pinned to `whole`.** Not because ranges stopped working — the worker
//   answers them locally and would answer every one — but because with the object already on disk
//   `whole` strictly dominates: it costs the same nothing, and it puts the DECODED body in the
//   resident map, after which every later read in that locality group is a memcpy instead of a
//   round trip through the worker. Ranges exist to avoid over-fetching from a Range-less origin,
//   and once the over-fetch is paid once, forever, there is nothing left for them to save. Both
//   probes are skipped with it, which also takes two round trips out of boot.
//
// `?nosw=1` turns all of that off and unregisters the worker, which is how the pre-worker path —
// and `wenilla-host --no-ranges`, the Range-less emulation the fallback exists for — stays
// exercisable.
//
// ## The decode worker (`web/packworker.js`)
//
// Warming a pack used to mean putting its WIRE bytes somewhere — the service worker's cache — and
// leaving the decode to the first read that wanted it, which ran in Rust, in the first update's
// catalog task, on the thread that draws. `warmPack` closes that: `packworker.js` fetches and
// decodes off-thread and posts the body back as a transferable `ArrayBuffer`, which lands in the
// resident map below at zero copy. A prefetched pack is therefore *decoded and resident* before
// `init()`, and the ~60 synchronous `Chain::read` sites that follow are memcpys.
//
// It is an accelerator, never a dependency. No `Worker`, a wasm that will not load, a worker that
// dies mid-session: every pending warm settles as "not resident" and the read path does exactly
// what it did before. `?noworker=1` forces that state for bisecting.
//
// Page contract: a plain global, `window.__wenilla_packs`, like every other seam this client uses
// (`__wenilla_env`, `__wenilla_progress`, `__wenilla_boottrace`). Deliberately not a wasm-bindgen
// module import: the client must still run on a page that ships none of this — the resident map is
// then always empty, every read re-fetches its pack, and `wenilla-host --www web/dist` stays a
// usable way to bisect a rendering bug.

/// Resident budget. Packs are ~0.6 MB decoded at the container's measured p50, so this is a few
/// hundred of them — comfortably the whole boot set plus a zone's worth of terrain.
const RESIDENT_BUDGET_BYTES = 256 * 1024 * 1024;
/// Fetch pool width for the prefetch. Matches boot.js's old per-name pool; the objects are ~50x
/// larger now, so this is bandwidth-bound rather than round-trip-bound and the number matters less.
const PREFETCH_CONCURRENCY = 6;
/// How many warms may be in flight at once — and, therefore, the reason `_warmQueue` exists at all.
///
/// Before this there was no queue: every `warmPack` posted to the worker (or started a fetch) the
/// instant it was asked for, and the ORDER packs arrived in was whatever order the browser's own
/// six-connections-per-host limit happened to drain. That is fine when every pack is equally
/// wanted. It is not fine at a zone boundary, where a few hundred texture warms are asked for in
/// the same frame as the one `.adt` and the three `.wmo` groups that decide whether there is a
/// floor under the player — those four then queue behind the art, arrive seconds late, and the
/// body walks onto ground that has no collider yet.
///
/// Six matches what the browser would have allowed anyway, so throughput is unchanged; what
/// changes is that WE choose which six, by `priority` (see `warmPack`).
const WARM_CONCURRENCY = 6;
/// Warm priority: **collision-bearing reads** — terrain tiles, WMO roots and groups, M2 headers
/// (their bounds and collision hulls) — go ahead of everything else. The classifier is Rust's
/// (`benilla_formats::webpack::warm_priority`), which is where the extension law already lives;
/// this file only orders what it is told.
const PRIORITY_GEOMETRY = 0;
/// Everything else: textures, sounds, DBCs, UI art. The default when a caller names no priority.
const PRIORITY_NORMAL = 1;
/// Stop writing Cache Storage at this fraction of the origin's quota. Going over does not fail
/// loudly — the browser evicts something, possibly the packs we just wrote — so leaving headroom is
/// how the cache stays useful rather than thrashing.
const QUOTA_CEILING = 0.8;
/// Where the probe result is remembered per origin, so a repeat visit starts with the right policy
/// instead of paying a demotion to learn it again.
const POLICY_KEY = 'wenilla-range-policy';
/// The decode worker's script, beside this one at the dist root (Trunk `copy-file`).
const WORKER_URL = './packworker.js';
/// How long to wait for the worker to say it has parsed the index. It is a wasm instantiation of a
/// ~106 KB module plus an index parse, so this is tens of milliseconds in practice; the bound
/// exists so a worker that never answers costs a boot delay instead of a boot.
const WORKER_OPEN_TIMEOUT_MS = 10000;

/// `p/<hi>/<id>.bpk` — the twin of `benilla_pack::pack_path`. The index carries no path table (the
/// path IS the id), so this law exists in exactly two places and they must agree; the container's
/// own `pack_id` header field is what catches it if they ever stop agreeing.
function packPath(id) {
  const hi = ((id >> 8) & 0xff).toString(16).padStart(2, '0');
  return `p/${hi}/${id.toString(16).padStart(4, '0')}.bpk`;
}

const packs = {
  /// `{origin}/data`, no trailing slash. Set by bootstrap().
  base: '',
  /// 'range' | 'whole'. Read by Rust before every miss; written by Rust on a demotion (a range
  /// request answered with a full 200) and by reprobe() on a promotion.
  policy: 'whole',
  /// The container's build id as a hex string — the cache's identity, in `sw.js` and here alike.
  buildId: '',
  /// Is `sw.js` controlling this page? Set by `registerWorker`. When true this file does no caching
  /// of its own and the policy is pinned to `whole`; see the header.
  sw: false,
  /// `index.bpi`'s bytes, handed to Rust at `Chain::open` so the 1.6 MB index never goes through
  /// the synchronous XHR path's per-character body decode.
  index: null,
  /// `listfile.txt` as text, likewise. Only `load_macro_icons` reads it.
  listfile: null,
  /// Generated pack lists: `{boot: {packs: [[id, wireBytes], …], bytes}, world: {…}}`.
  manifest: null,
  /// The warm priorities, named — the values Rust passes to `warmPack`/`prefetch`. Exposed so the
  /// seam is readable from a console and so the two constants have exactly one definition.
  PRIORITY: { geometry: PRIORITY_GEOMETRY, normal: PRIORITY_NORMAL },

  // ---- the resident map ------------------------------------------------------------------

  /// packId -> Uint8Array of the pack's DECODED body. Insertion order is the LRU order; a hit
  /// re-inserts, so the oldest key is genuinely the least recently used.
  _resident: new Map(),
  _residentBytes: 0,

  /// One frame's bytes out of a resident pack, or null if the pack is not resident. A subarray, so
  /// no copy happens on this side; Rust copies the frame — and only the frame — into wasm memory.
  ///
  /// The hot path of the whole client: every chain read that hits a warm pack is this.
  slice(packId, off, len) {
    const body = this._resident.get(packId);
    if (body === undefined) return null;
    if (off + len > body.length) return null;
    // Re-insert to move it to the young end of the LRU. Two hash operations against a memcpy of
    // the frame, so it does not show up.
    this._resident.delete(packId);
    this._resident.set(packId, body);
    return body.subarray(off, off + len);
  },

  /// Is this pack's body already here? One `Map.has`, for the Rust prefetch path, which asks
  /// before it spends anything — `slice` would answer the same question but marshals a frame
  /// across the wasm boundary to do it.
  has(packId) {
    return this._resident.has(packId);
  },

  /// Unpack a synchronous XHR's **binary string** (one code unit per byte — the
  /// `charset=x-user-defined` contract) into the bytes it stands for.
  ///
  /// It lives here rather than in Rust because the string is a JS value and every way of getting
  /// one into wasm goes through UTF-8: wasm-bindgen would transcode the whole body on the way
  /// across (near-random bytes grow ~1.5x once every unit above 0x7F becomes two), Rust would copy
  /// that into a `String`, and `chars()` would decode it back — three passes to move bytes that
  /// were already bytes. Here the loop runs in the engine and the boundary sees one typed-array
  /// copy of exactly `len`.
  ///
  /// The lane it serves is the ~60 blocking `Chain::read` sites (`benilla_formats::web`), which are
  /// boot's and which cannot await. Rust keeps its own slower fallback for a page without this.
  unpackBinary(s) {
    const n = s.length;
    const a = new Uint8Array(n);
    for (let i = 0; i < n; i++) a[i] = s.charCodeAt(i) & 0xff;
    return a;
  },

  /// Take a decoded pack body from Rust and hold it. The bytes were copied out of wasm memory on
  /// the way in, so this array is ours and outlives the Vec it came from.
  put(packId, body) {
    if (this._resident.has(packId)) return;
    this._resident.set(packId, body);
    this._residentBytes += body.length;
    while (this._residentBytes > RESIDENT_BUDGET_BYTES && this._resident.size > 1) {
      const oldest = this._resident.keys().next().value;
      this._residentBytes -= this._resident.get(oldest).length;
      this._resident.delete(oldest);
    }
  },

  // ---- the decode worker -----------------------------------------------------------------

  /// The live `packworker.js`, or null. Public because `prefetch` branches on it and because it is
  /// the first thing to look at from a console when a boot is slower than it should be.
  worker: null,
  /// packId -> the job record for every warm that has been ASKED FOR — queued or in flight — and
  /// the dedup with it: two reads landing in the same unheld pack share one job rather than
  /// fetching it twice. A record carries `{promise, resolve, url, priority, started}`.
  _pending: new Map(),
  /// Asked-for warms that have not started yet, in arrival order; `_pumpWarms` picks the best
  /// priority out of it. An array rather than a heap because it is drained six at a time and is
  /// empty in steady state — a linear scan of a list that is usually zero-length costs nothing,
  /// and a heap here would be a data structure to maintain for no measurable win.
  _warmQueue: [],
  /// How many warms are actually in flight (started, not yet settled). Bounded by
  /// `WARM_CONCURRENCY`.
  _warmActive: 0,
  /// Does the worker fetch for itself? True only with `sw.js` in control, where caching is the
  /// service worker's job — otherwise the fetch stays here, where Cache Storage is. See
  /// `packworker.js`'s header for why that split exists rather than a second cache in the worker.
  _workerFetches: false,

  /// Have `packId` fetched, decoded and put in the resident map; resolves `true` once it is there.
  ///
  /// **`false` is not an error, it is "do it the old way".** No worker on this page, a 404, a
  /// worker that died — every caller (the prefetch pool below, `Chain::read_async` through
  /// `webpack::resident::warm`) falls back to the path it took before this file had a worker.
  ///
  /// `priority` orders the wait, not the work: a lower number starts sooner once more than
  /// `WARM_CONCURRENCY` warms are outstanding. A pack already asked for at a WORSE priority is
  /// promoted in place — the same read arriving again as "I need this for a collider" must not have
  /// to wait behind the queue it was already sitting in.
  warmPack(packId, url, priority = PRIORITY_NORMAL) {
    if (this._resident.has(packId)) return Promise.resolve(true);
    if (!this.worker) return Promise.resolve(false);
    const pending = this._pending.get(packId);
    if (pending) {
      if (priority < pending.priority) pending.priority = priority;
      return pending.promise;
    }
    let resolve;
    const promise = new Promise((r) => {
      resolve = r;
    });
    this._pending.set(packId, { promise, resolve, url, priority, started: false });
    this._warmQueue.push(packId);
    this._pumpWarms();
    return promise;
  },

  /// Start as many queued warms as the concurrency allows, best priority first (ties by arrival —
  /// the queue is scanned in order and only a STRICTLY better priority displaces the incumbent, so
  /// a burst of equal-priority reads keeps the order it was asked in).
  _pumpWarms() {
    // Re-entrancy guard, because `_startWarm` can settle synchronously (no worker) and every settle
    // pumps: without this a queue with a dead worker under it would recurse once per entry. Also the
    // reason the loop below re-reads `_warmActive` rather than trusting a local.
    if (this._pumping || !this.worker) return;
    this._pumping = true;
    try {
      this._pumpQueue();
    } finally {
      this._pumping = false;
    }
  },
  _pumping: false,

  /// `_pumpWarms`'s body, split out so the guard above has one exit to clear itself on.
  _pumpQueue() {
    while (this._warmActive < WARM_CONCURRENCY && this._warmQueue.length) {
      let best = 0;
      for (let i = 1; i < this._warmQueue.length; i++) {
        const a = this._pending.get(this._warmQueue[i]);
        const b = this._pending.get(this._warmQueue[best]);
        if (!b || (a && a.priority < b.priority)) best = i;
      }
      const packId = this._warmQueue.splice(best, 1)[0];
      const job = this._pending.get(packId);
      // Settled while it was still queued (the worker died under it) — nothing left to start.
      if (!job) continue;
      job.started = true;
      this._warmActive++;
      this._startWarm(packId, job);
    }
  },

  /// One started warm: hand it to the worker, either as a fetch it does itself or as wire bytes
  /// this side fetched. Unchanged from what `warmPack` used to do inline — only *when* it runs is
  /// new.
  _startWarm(packId, job) {
    if (!this.worker) return this._settle(packId, false, 'the worker went away');
    if (this._workerFetches) {
      this.worker.postMessage({ type: 'fetch', id: packId });
      return;
    }
    // `_fetchWireOnce`, not `fetchWire`: the buffer is TRANSFERRED to the worker and this side
    // loses it, so it must not be one another waiter is holding. The two never race in practice —
    // `read_async` asks here first and only reaches `fetchWire` when there is no worker — and if
    // they somehow did, the cost is a second fetch of the same object, not a detached buffer.
    this._fetchWireOnce(packId, job.url).then(
      (bytes) => {
        if (!this.worker) return this._settle(packId, false, 'the worker went away');
        this.worker.postMessage({ type: 'decode', id: packId, wire: bytes.buffer }, [bytes.buffer]);
      },
      (e) => this._settle(packId, false, e)
    );
  },

  /// Packs a warm has already failed on — a 404, a worker that died mid-job, a body that would not
  /// decode. Retrying those forever is what a fire-and-forget prefetch would otherwise do: nothing
  /// ever settles them, so nothing ever stops asking.
  _failed: new Set(),

  /// Can a warm of this pack be expected to arrive? The **non-blocking read lane's precondition**:
  /// Rust asks before it answers "not yet", because a caller told to retry a warm that can never
  /// land would retry forever and the icon would simply never appear. `false` sends that read back
  /// to the blocking path it took before this lane existed — slower, and exactly as correct.
  ///
  /// This is the "accelerator, never a dependency" law of the decode worker, restated for the one
  /// caller that would otherwise depend on it.
  canWarm(packId) {
    return !!this.worker && !this._failed.has(packId);
  },

  /// `warmPack` with the answer thrown away — the **non-blocking read lane's** whole mechanism
  /// (`benilla_formats::webpack::resident::prefetch`).
  ///
  /// Rust reaches this from two places that have no await to spend: a frame-thread read whose pack
  /// is not resident, which reports "not yet" and retries a frame later, and a caller saying it
  /// will want a blob before it does. Neither wants a Promise, and a UI system asking for the same
  /// not-yet-arrived icon at 60 Hz must not cost 60 of them a second — so the three cheap outcomes
  /// (already here, already coming, already known bad) return before one is made.
  ///
  /// Deliberately returns nothing. A caller that could use the answer should call `warmPack`.
  prefetch(packId, url, priority = PRIORITY_NORMAL) {
    if (this._resident.has(packId)) return;
    if (!this.canWarm(packId)) return;
    // A pack already asked for is not re-asked — but it IS promoted if this ask is the more urgent
    // one, which is the same in-place promotion `warmPack` does for a caller that wants the answer.
    const already = this._pending.get(packId);
    if (already) {
      if (priority < already.priority) already.priority = priority;
      return;
    }
    this.warmPack(packId, url, priority).then(
      (resident) => {
        if (!resident) this._failed.add(packId);
      },
      () => this._failed.add(packId)
    );
  },

  /// Finish one warm. Every path out of `warmPack` ends here exactly once, including the failures,
  /// because a pending job nothing resolves is a prefetch that never reports progress.
  _settle(packId, resident, error) {
    const pending = this._pending.get(packId);
    if (!pending) return;
    this._pending.delete(packId);
    if (pending.started) {
      this._warmActive--;
    } else {
      // Settled before it ever started (the worker died with a queue behind it). Its slot was never
      // taken, so only the queue entry has to go.
      const at = this._warmQueue.indexOf(packId);
      if (at >= 0) this._warmQueue.splice(at, 1);
    }
    if (error) console.warn(`wenilla: pack ${packId} —`, error);
    pending.resolve(resident);
    // A freed slot is the only thing that lets the next queued warm start, so every settle pumps.
    this._pumpWarms();
  },

  // ---- fetching --------------------------------------------------------------------------

  /// In-flight whole-object fetches, keyed by URL. `sw.js` dedupes at the network layer, but two
  /// concurrent `read_async`s for different names in the same pack still each want the bytes, and
  /// without this each pays its own Cache Storage read and its own copy across the wasm boundary.
  /// It is also the only dedup there is on a page with no worker.
  _inflight: new Map(),

  /// A whole `.bpk`. Through the service worker when there is one — which is where the permanent
  /// copy lives and where the synchronous lane will find it too — and through this file's own
  /// Cache Storage when there is not. The async lane's fetch (`benilla-assets`' AssetReader).
  fetchWire(packId, url) {
    const pending = this._inflight.get(url);
    if (pending) return pending;
    const job = this._fetchWireOnce(packId, url);
    this._inflight.set(url, job);
    job.catch(() => {}).finally(() => this._inflight.delete(url));
    return job;
  },

  async _fetchWireOnce(packId, url) {
    const cached = await this._cacheMatch(url);
    if (cached) return cached;
    const r = await fetch(url);
    if (!r.ok) throw new Error(`pack ${packId}: HTTP ${r.status}`);
    const bytes = new Uint8Array(await r.arrayBuffer());
    await this._cachePut(url, bytes);
    return bytes;
  },

  /// One frame's byte range, reporting whether the host actually honoured it. `ranged: false` means
  /// a 200 with the whole object came back — not an error, just a static host on a cache miss — and
  /// Rust absorbs that body rather than throwing away a response already paid for.
  async fetchFrame(packId, url, start, end) {
    const r = await fetch(url, { headers: { Range: `bytes=${start}-${end}` } });
    if (!r.ok) throw new Error(`pack ${packId}: HTTP ${r.status}`);
    const bytes = new Uint8Array(await r.arrayBuffer());
    if (r.status === 206) return { ranged: true, bytes };
    // A full body arrived on a range request; keep it, since the next miss in this pack would
    // otherwise re-download the same object.
    await this._cachePut(url, bytes);
    return { ranged: false, bytes };
  },

  /// The URL one pack is served at.
  url(packId) {
    return `${this.base}/${packPath(packId)}`;
  },

  // ---- Cache Storage ---------------------------------------------------------------------

  _cache: null,

  /// The direct Cache Storage handle — `false` whenever this file must not write one.
  ///
  /// `sw.js` in control is one of the two ways it is `false`, and the important one: the worker has
  /// already stored every `/data` response that passed through it, so opening a second cache here
  /// would put the same 3.3 GiB corpus against the same origin quota twice, and the copy it evicted
  /// to make room might be the worker's — the only one the synchronous lane can read.
  async _openCache() {
    if (this._cache !== null) return this._cache;
    if (this.sw) {
      this._cache = false;
      return false;
    }
    try {
      this._cache = await caches.open(`wenilla-packs-${this.buildId}`);
    } catch (_) {
      this._cache = false; // no Cache Storage here (private mode, disabled storage)
    }
    return this._cache;
  },

  async _cacheMatch(url) {
    const cache = await this._openCache();
    if (!cache) return null;
    try {
      const hit = await cache.match(url);
      return hit ? new Uint8Array(await hit.arrayBuffer()) : null;
    } catch (_) {
      return null;
    }
  },

  async _cachePut(url, bytes) {
    const cache = await this._openCache();
    if (!cache || !(await this._roomToCache(bytes.length))) return;
    try {
      await cache.put(url, new Response(bytes));
    } catch (_) {
      /* quota, or a browser that refuses; the network path is still correct */
    }
  },

  _quota: null,

  async _roomToCache(bytes) {
    if (!navigator.storage || !navigator.storage.estimate) return true;
    // Re-estimating per object would be a syscall per pack; sample and then account locally.
    if (this._quota === null || this._quota.n > 64) {
      try {
        const e = await navigator.storage.estimate();
        this._quota = { usage: e.usage || 0, quota: e.quota || 0, n: 0 };
      } catch (_) {
        this._quota = { usage: 0, quota: 0, n: 0 };
      }
    }
    this._quota.n += 1;
    this._quota.usage += bytes;
    return !this._quota.quota || this._quota.usage < this._quota.quota * QUOTA_CEILING;
  },
};

window.__wenilla_packs = packs;
export default packs;

/// Install the permanence worker, fetch the index, the listfile and the boot pack set, and — where
/// there is no worker to make the question moot — measure whether this host does ranges.
///
/// Called by `boot.js` BEFORE `init()`, and awaited, for the same reason the old per-name prefetch
/// was: the client's first update is a pile of synchronous chain reads in one rAF task, and paying
/// for them here — with the page responsive and a progress bar moving — costs the same wall clock
/// and none of the frozen tab. `onProgress(doneBytes, totalBytes)`.
///
/// `opts.prefetch = false` (the `?boottrace=1` / `?noprefetch=1` levers) skips **only the pack
/// warm**. The index is not optional: `Chain::open` needs it, and leaving it to the synchronous
/// fallback would make those two switches measure the fallback rather than the thing they exist to
/// measure.
///
/// `opts.sw = false` (the `?nosw=1` lever) skips the service worker and unregisters any already
/// installed, putting the page back on the pre-worker path. `opts.worker = false` (`?noworker=1`)
/// skips the decode worker, which puts every pack decode back on the frame thread — the A/B lever
/// for the phase-6 change, and the bisect for a suspected decode bug.
export async function bootstrap(base, onProgress = () => {}, opts = {}) {
  packs.base = base;

  // Asked early and NOT awaited. Early because the sooner the grant lands the smaller the window in
  // which the corpus is evictable; not awaited because Firefox answers `persist()` with a user
  // prompt, and a boot that blocks until someone notices a doorhanger is a worse bug than the one
  // this is preventing. Nothing depends on the answer either way: the flag is origin-wide and
  // applies to what is already stored, so a late grant protects the packs written before it.
  //
  // Origin-wide also means this is not only about the corpus. The client keeps its state folder —
  // CVars, key bindings, macros, layouts, the remembered account name — in `localStorage`, one
  // entry per file (benilla-app/src/local_state.rs), and eviction takes an origin's quota storage
  // as a unit: the same ask is what keeps a returning player off default keybinds.
  requestPersistence();
  packs.sw = await registerWorker(opts.sw !== false);

  // The MANIFEST FIRST, and this order is load-bearing when the worker is in control. It carries
  // `build_id`, which is what tells the worker whether the corpus it has on disk is still the
  // corpus this origin serves; sending it before the first cache-first read means a stale container
  // is dropped BEFORE anything can be answered out of it. `boot-packs.json` is also the one `/data`
  // object the worker keeps network-first for exactly this reason.
  packs.manifest = await fetchJson(`${base}/boot-packs.json`);
  packs.buildId = (packs.manifest && packs.manifest.build_id) || '';
  if (packs.buildId) await syncBuild(packs.buildId);

  packs.index = await fetchIndex(base);
  if (!packs.buildId) {
    // No manifest — an old container, or an origin that lost the file. The index carries the same
    // id, so the sync still happens, just a step late; if it purged a mismatched cache then the
    // index that came back may have been the stale one, so it is re-read against the empty cache.
    packs.buildId = readBuildId(packs.index);
    const synced = await syncBuild(packs.buildId);
    if (synced && synced.purged) packs.index = await fetchIndex(base);
  }

  // With the worker in control every object is one origin hit and then permanent, so a range saves
  // nothing and costs the residency that makes the next few hundred reads in the pack free. Pinned
  // in memory only: `localStorage` remembers what was MEASURED about this origin, and a later
  // `?nosw=1` run must still find that answer rather than this one.
  if (packs.sw) packs.policy = 'whole';
  else {
    const remembered = safeLocalGet(POLICY_KEY);
    if (remembered === 'range' || remembered === 'whole') packs.policy = remembered;
  }

  // After the index — it is what the worker is opened *with* — and before the prefetch, which is
  // the whole reason it exists. A worker that will not start leaves `packs.worker` null and every
  // path below reads as it did before phase 6.
  await startWorker(opts.worker !== false);

  const boot = (packs.manifest && packs.manifest.boot) || { packs: [], bytes: 0 };
  if (opts.prefetch === false) return onProgress(0, 0);

  // The probe targets a pack boot needs anyway, so whichever way the response comes back it is not
  // a wasted request — and the 16-byte ask is free if it comes back as one.
  if (!packs.sw && boot.packs.length) await probe(packs.url(boot.packs[0][0]));

  await prefetch(boot.packs, onProgress, [`${base}/listfile.txt`]);
  // Now that the edge has stored these objects, ask again: this is the state a static host starts
  // answering 206 in, and it is the only promotion path (a `whole`-policy read never issues a
  // range request, so Rust can never observe a 206 on its own).
  if (!packs.sw && boot.packs.length && packs.policy !== 'range') {
    await probe(packs.url(boot.packs[0][0]));
  }
}

async function fetchIndex(base) {
  const r = await fetch(`${base}/index.bpi`);
  if (!r.ok) throw new Error(`no container at ${base}/index.bpi (HTTP ${r.status})`);
  return new Uint8Array(await r.arrayBuffer());
}

/// The world-entry pack set, warmed after the client reports `ready` (see boot.js). Same shape as
/// the boot set and deliberately separate: it is what the first in-game draw resolves, and it is
/// warmed while the player is still at the glue screens.
export async function prefetchWorld(onProgress = () => {}) {
  const world = (packs.manifest && packs.manifest.world) || { packs: [], bytes: 0 };
  await prefetch(world.packs, onProgress);
}

// ---- the service worker ------------------------------------------------------------------

/// Root-scoped so it can see `/data/*` from any page that hosts the client — `web/index.html` at
/// `/`, and any hosting page that boots the client from a subpath.
const SW_URL = '/sw.js';
/// How long to wait for a first-visit worker to claim this page. It is `clients.claim()` in an
/// `activate` handler, so this is milliseconds in practice; the bound exists so a worker that
/// somehow never activates costs a delay instead of a boot.
const SW_CLAIM_TIMEOUT_MS = 5000;
/// Likewise for the build handshake: a worker that does not answer is one the page proceeds
/// without, on the pre-worker path's terms.
const SW_MESSAGE_TIMEOUT_MS = 5000;

/// Install `sw.js` and report whether it is actually CONTROLLING this page — which is the only
/// state that matters, since a registered-but-not-controlling worker sees none of our fetches and
/// pinning the policy for it would be a lie.
async function registerWorker(enabled) {
  if (!enabled) {
    await unregisterWorker();
    // Unregistering does NOT un-control the page that is already loaded: a worker installed on an
    // earlier visit keeps serving this document's fetches until it navigates. So `?nosw=1` takes
    // full effect on the NEXT load, and reporting the truth here — rather than a flat `false` — is
    // what stops this load from opening a second cache beside the one still answering it.
    return !!(navigator.serviceWorker && navigator.serviceWorker.controller);
  }
  // `isSecureContext` rather than a protocol test: `http://127.0.0.1` is secure and is how
  // `wenilla-host` is run, while `http://` to a LAN address is not and has no service workers at
  // all. The page must still boot there, on the pre-worker path.
  if (!('serviceWorker' in navigator) || !self.isSecureContext) return false;
  try {
    await navigator.serviceWorker.register(SW_URL, { scope: '/' });
  } catch (e) {
    console.warn('wenilla: service worker registration failed —', e);
    return false;
  }
  if (navigator.serviceWorker.controller) return true;
  return await new Promise((resolve) => {
    const finish = (controlled) => {
      clearTimeout(timer);
      navigator.serviceWorker.removeEventListener('controllerchange', onChange);
      resolve(controlled);
    };
    const onChange = () => finish(!!navigator.serviceWorker.controller);
    const timer = setTimeout(() => finish(false), SW_CLAIM_TIMEOUT_MS);
    navigator.serviceWorker.addEventListener('controllerchange', onChange);
  });
}

async function unregisterWorker() {
  if (!('serviceWorker' in navigator)) return;
  try {
    const registrations = await navigator.serviceWorker.getRegistrations();
    await Promise.all(registrations.map((r) => r.unregister()));
  } catch (_) {
    /* nothing to undo */
  }
}

/// Tell the worker which container this is, and wait for it to say it has reconciled — see
/// `sw.js`'s `syncBuild`. Resolves to `{ok, purged}`, or `null` when there is no worker to ask or
/// it did not answer in time.
///
/// Awaited rather than fired and forgotten: the answer gates the first cache-first read, and a page
/// that raced ahead could be handed an index from a container the origin no longer serves.
function syncBuild(buildId) {
  const worker = navigator.serviceWorker && navigator.serviceWorker.controller;
  if (!worker || !buildId) return Promise.resolve(null);
  return new Promise((resolve) => {
    const channel = new MessageChannel();
    const timer = setTimeout(() => resolve(null), SW_MESSAGE_TIMEOUT_MS);
    channel.port1.onmessage = (e) => {
      clearTimeout(timer);
      resolve(e.data || null);
    };
    try {
      worker.postMessage({ type: 'wenilla-build', buildId }, [channel.port2]);
    } catch (_) {
      clearTimeout(timer);
      resolve(null);
    }
  });
}

// ---- the decode worker -------------------------------------------------------------------

/// Start `packworker.js` and open the container inside it. Resolves to the worker, or to `null`
/// for every way it can fail to be useful — no `Worker` constructor, a script that will not load, a
/// wasm that will not instantiate, an index it cannot parse, or a silence longer than
/// [`WORKER_OPEN_TIMEOUT_MS`]. Nothing downstream branches on *why*.
///
/// The build-id check at the end is the one hard refusal. Everything else degrades to slower; a
/// worker decoding against a different container's index would hand back plausible bytes from the
/// wrong offsets, which is the failure mode nothing downstream could detect.
async function startWorker(enabled) {
  if (!enabled || typeof Worker === 'undefined' || !packs.index) return null;
  let worker;
  try {
    worker = new Worker(WORKER_URL);
  } catch (e) {
    console.warn('wenilla: pack worker failed to start —', e);
    return null;
  }
  let finishOpen = () => {};
  const opened = new Promise((resolve) => {
    const onMessage = (e) => {
      const m = e.data;
      if (m && (m.type === 'opened' || m.type === 'failed')) finishOpen(m);
    };
    const timer = setTimeout(() => finishOpen(null), WORKER_OPEN_TIMEOUT_MS);
    finishOpen = (answer) => {
      clearTimeout(timer);
      worker.removeEventListener('message', onMessage);
      resolve(answer);
    };
    worker.addEventListener('message', onMessage);
  });

  // Registered before the first message, and it ends the handshake as well as reporting: a worker
  // that throws while loading its own script never answers, and without this the boot would sit on
  // the ten-second timeout to learn what this already knows.
  worker.onerror = (e) => {
    console.warn('wenilla: pack worker error —', (e && e.message) || e);
    finishOpen(null);
    dropWorker('the pack worker failed');
  };

  // A COPY of the index, transferred. The page keeps its own — `Chain::open` reads it out of
  // `packs.index` — and 1.6 MB duplicated once at boot is the price of the worker knowing each
  // pack's codec and decoded size, which are index fields a `.bpk` does not restate.
  const copy = packs.index.slice().buffer;
  worker.postMessage({ type: 'open', base: packs.base, index: copy }, [copy]);

  const answer = await opened;
  if (!answer || answer.type !== 'opened') {
    console.warn('wenilla: pack worker did not open the container —', (answer && answer.error) || 'no answer');
    worker.terminate();
    return null;
  }
  if (packs.buildId && answer.buildId !== packs.buildId) {
    console.warn(
      `wenilla: pack worker opened container ${answer.buildId}, page has ${packs.buildId} — not using it`
    );
    worker.terminate();
    return null;
  }
  worker.addEventListener('message', onWorkerMessage);
  packs.worker = worker;
  // Only with `sw.js` in control does the worker fetch for itself; otherwise Cache Storage lives
  // here and so does the fetch. See `packworker.js`'s header.
  packs._workerFetches = packs.sw;
  return worker;
}

/// The worker's answers. A `body` is adopted straight into the resident map — `m.body` is a
/// transferred `ArrayBuffer`, so this is a view over bytes that were never copied on this thread.
function onWorkerMessage(e) {
  const m = e.data;
  if (!m) return;
  if (m.type === 'body') {
    packs.put(m.id, new Uint8Array(m.body));
    packs._settle(m.id, true);
  } else if (m.type === 'miss') {
    packs._settle(m.id, false, m.error);
  }
}

/// Lose the worker and settle everything waiting on it as "not resident", so a warm in flight when
/// it died becomes a slow read rather than a promise nobody ever resolves.
function dropWorker(reason) {
  const worker = packs.worker;
  packs.worker = null;
  if (worker) worker.terminate();
  for (const id of Array.from(packs._pending.keys())) packs._settle(id, false, reason);
}

/// Ask the browser to exempt this origin's storage from eviction.
///
/// A "no" is not a failure — every path through this file and `sw.js` is correct against an empty
/// cache — but the ask is worth making, because without a grant the corpus is merely "best-effort"
/// storage the browser may evict under disk pressure, and re-downloading 3.3 GiB is the exact cost
/// all of this exists to remove. Chrome grants it silently on an engaged origin; Firefox prompts,
/// which is why the caller does not await this.
///
/// `persisted()` first so an origin that already has the grant never re-prompts.
async function requestPersistence() {
  if (!navigator.storage || !navigator.storage.persist) return false;
  try {
    if (navigator.storage.persisted && (await navigator.storage.persisted())) return true;
    return await navigator.storage.persist();
  } catch (_) {
    return false;
  }
}

/// One `Range: bytes=0-15` against a real pack. 206 with exactly 16 bytes back is the only proof
/// that counts; anything else means whole-object fetches, which are never wrong, only bigger.
async function probe(url) {
  try {
    const r = await fetch(url, { headers: { Range: 'bytes=0-15' } });
    const body = await r.arrayBuffer();
    packs.policy = r.status === 206 && body.byteLength === 16 ? 'range' : 'whole';
  } catch (_) {
    packs.policy = 'whole';
  }
  safeLocalSet(POLICY_KEY, packs.policy);
}

/// Warm a list of `[packId, wireBytes]` (plus any extra URLs) through a fixed-size pool, reporting
/// bytes rather than files — an object is ~0.6 MB, so "12 of 31" says much less than "8 of 19 MB".
///
/// Failures are counted as done and otherwise ignored: a miss means that pack loads the slow way,
/// which is exactly the behaviour of a page that never prefetched at all.
async function prefetch(list, onProgress, extraUrls = []) {
  const jobs = list.map(([id, bytes]) => ({ id, bytes, url: packs.url(id) }));
  for (const url of extraUrls) jobs.push({ id: null, bytes: 0, url });
  const total = jobs.reduce((n, j) => n + j.bytes, 0);
  if (!jobs.length) return onProgress(0, 0);
  let done = 0;
  onProgress(0, total);
  const queue = jobs.slice();
  const worker = async () => {
    for (;;) {
      const job = queue.shift();
      if (job === undefined) return;
      try {
        if (job.id === null) {
          // The listfile rides along: it is the one side file the client fetches lazily, and
          // fetching it here means `Chain::list` never blocks on it.
          const r = await fetch(job.url);
          if (r.ok) packs.listfile = await r.text();
        } else if (packs.worker) {
          // Through the worker, so the pack lands DECODED in the resident map and the first read
          // of anything in it is a memcpy. `false` back means it could not be warmed that way;
          // a prefetch miss is already a non-event (the read path re-fetches), so it is not
          // retried here — retrying would only pay for the same failure twice before boot.
          await packs.warmPack(job.id, job.url);
        } else {
          await packs.fetchWire(job.id, job.url);
        }
      } catch (_) {
        /* offline blip, 404 drift — the read path deals with it */
      }
      done += job.bytes;
      onProgress(done, total);
    }
  };
  await Promise.all(Array.from({ length: PREFETCH_CONCURRENCY }, worker));
}

/// `index.bpi`'s build id: the u64 at offset 48, as hex. Read here rather than passed down from
/// Rust because Cache Storage has to be namespaced before the first pack is fetched, which is
/// before the wasm module exists.
function readBuildId(bytes) {
  const view = new DataView(bytes.buffer, bytes.byteOffset, bytes.byteLength);
  const lo = view.getUint32(48, true);
  const hi = view.getUint32(52, true);
  return hi.toString(16).padStart(8, '0') + lo.toString(16).padStart(8, '0');
}

async function fetchJson(url) {
  try {
    const r = await fetch(url);
    return r.ok ? await r.json() : null;
  } catch (_) {
    return null;
  }
}

// localStorage throws outright in some privacy configurations rather than merely being empty.
function safeLocalGet(key) {
  try {
    return localStorage.getItem(key);
  } catch (_) {
    return null;
  }
}

function safeLocalSet(key, value) {
  try {
    localStorage.setItem(key, value);
  } catch (_) {
    /* nothing to do; the probe just runs again next visit */
  }
}
