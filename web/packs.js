/// Install the permanence worker, fetch the index, the listfile and the boot pack set, and — where
/// there is no worker to make the question moot — measure whether this host does ranges.
///
/// Called by `boot.js` BEFORE `init()`, and awaited, for the same reason the old per-name prefetch
/// was: the client's first update is a pile of synchronous chain reads in one rAF task, and paying
/// for them here — with the page responsive and a progress bar moving — costs the same wall clock
/// and none of the frozen tab. `onProgress(doneBytes, totalBytes)`.
///
/// `opts.prefetch = false` (the `?boottrace=1` / `?noprefetch=1` levers) skips **only the pack
/// warm**. The index is not optional: `Chain::open` needs it, and leaving it to the synchronous
/// fallback would make those two switches measure the fallback rather than the thing they exist to
/// measure.
///
/// `opts.sw = false` (the `?nosw=1` lever) skips the service worker and unregisters any already
/// installed, putting the page back on the pre-worker path. `opts.worker = false` (`?noworker=1`)
/// skips the decode worker, which puts every pack decode back on the frame thread — the A/B lever
/// for the phase-6 change, and the bisect for a suspected decode bug.
export async function bootstrap(base, onProgress = () => {}, opts = {}) {
  packs.base = base;

  // Asked early and NOT awaited. Early because the sooner the grant lands the smaller the window in
  // which the corpus is evictable; not awaited because Firefox answers `persist()` with a user
  // prompt, and a boot that blocks until someone notices a doorhanger is a worse bug than the one
  // this is preventing. Nothing depends on the answer either way: the flag is origin-wide and
  // applies to what is already stored, so a late grant protects the packs written before it.
  //
  // Origin-wide also means this is not only about the corpus. The client keeps its state folder —
  // CVars, key bindings, macros, layouts, the remembered account name — in `localStorage`, one
  // entry per file (benilla-app/src/local_state.rs), and eviction takes an origin's quota storage
  // as a unit: the same ask is what keeps a returning player off default keybinds.
  requestPersistence();
  packs.sw = await registerWorker(opts.sw !== false);

  // The MANIFEST FIRST, and this order is load-bearing when the worker is in control. It carries
  // `build_id`, which is what tells the worker whether the corpus it has on disk is still the
  // corpus this origin serves; sending it before the first cache-first read means a stale container
  // is dropped BEFORE anything can be answered out of it. `boot-packs.json` is also the one `/data`
  // object the worker keeps network-first for exactly this reason.
  packs.manifest = await fetchJson(`${base}/boot-packs.json`);
  packs.buildId = (packs.manifest && packs.manifest.build_id) || '';
  if (packs.buildId) await syncBuild(packs.buildId);

  packs.index = await fetchIndex(base);
  if (!packs.buildId) {
    // No manifest — an old container, or an origin that lost the file. The index carries the same
    // id, so the sync still happens, just a step late; if it purged a mismatched cache then the
    // index that came back may have been the stale one, so it is re-read against the empty cache.
    packs.buildId = readBuildId(packs.index);
    const synced = await syncBuild(packs.buildId);
    if (synced && synced.purged) packs.index = await fetchIndex(base);
  }

  // With the worker in control every object is one origin hit and then permanent, so a range saves
  // nothing and costs the residency that makes the next few hundred reads in the pack free. Pinned
  // in memory only: `localStorage` remembers what was MEASURED about this origin, and a later
  // `?nosw=1` run must still find that answer rather than this one.
  if (packs.sw) packs.policy = 'whole';
  else {
    const remembered = safeLocalGet(POLICY_KEY);
    if (remembered === 'range' || remembered === 'whole') packs.policy = remembered;
  }

  // After the index — it is what the worker is opened *with* — and before the prefetch, which is
  // the whole reason it exists. A worker that will not start leaves `packs.worker` null and every
  // path below reads as it did before phase 6.
  await startWorker(opts.worker !== false);

  // The optional layer, BEFORE the prefetch's early return. `?boottrace=1` and `?noprefetch=1` both
  // skip the pack warm and neither may skip the layer's INDEX: a manifest capture with the updated
  // character models on has to run against the composite the player would see, and a client whose
  // layer never opened reads the original art and records the original names. `bootstrapHd` honours
  // `opts.prefetch` itself — it opens the container and warms nothing.
  await bootstrapHd(opts);

  const boot = (packs.manifest && packs.manifest.boot) || { packs: [], bytes: 0 };
  if (opts.prefetch === false) return onProgress(0, 0);

  // The probe targets a pack boot needs anyway, so whichever way the response comes back it is not
  // a wasted request — and the 16-byte ask is free if it comes back as one.
  if (!packs.sw && boot.packs.length) await probe(packs.url(boot.packs[0][0]));

  // The glue sets ride the same bar: the corpus's, the updated character models' when that layer
  // is open, and — for a player whose last realm was Turtle WoW — the Turtle layer's and its
  // reforged art's (`flavorGlue`). Sized up front so the bar is one honest total.
  const glue = await glueSets(opts);
  const glueBytes = glue.reduce((n, [, bytes]) => n + bytes, 0);
  const total = boot.bytes + glueBytes;
  await prefetch(boot.packs, (done) => onProgress(done, total), [`${base}/listfile.txt`]);
  await persistPacks(glue, (done) => onProgress(boot.bytes + done, total));
  // Now that the edge has stored these objects, ask again: this is the state a static host starts
  // answering 206 in, and it is the only promotion path (a `whole`-policy read never issues a
  // range request, so Rust can never observe a 206 on its own).
  if (!packs.sw && boot.packs.length && packs.policy !== 'range') {
    await probe(packs.url(boot.packs[0][0]));
  }
}

/// Open the updated-character-model layer, if the player has it on and this origin serves one.
///
/// **The whole point of this function is the early return.** With the option off it makes no
/// request at all: no index, no manifest, no HEAD to find out whether `/data-hd` is even hosted.
/// That is the feature — the layer is ~1.5 GiB of objects, and a player who never turned it on must
/// not pay a byte or a round trip for it.
///
/// With it on, a missing container is NOT an error. `/data-hd` is hosted separately from the
/// corpus (`scripts/stage-packs.sh` links it only if it was built), so "the option is on and this
/// origin has no layer" is an ordinary state of an ordinary site, and the right answer to it is
/// the game in its original art plus one console line. `Chain::open_layered` says the same thing on
/// the Rust side for the same reason.
async function bootstrapHd(opts = {}) {
  if (!hdWanted()) return;
  // The shared open (`packs.openLayer`), which a later turn-on at the options window takes too:
  // index, then `boot-packs.json` and the listfile, then the layer made real (`hdBase`, `hdIndex`),
  // then its container in the decode worker, then — unless `opts.prefetch === false` — its boot
  // packs, offset into the layer's key space.
  const opened = await packs.openLayer('hd', { prefetch: opts.prefetch, glue: false });
  if (!opened) {
    console.warn('wenilla: updated character models are on — running on the original art');
  }
}

/// Hand a layer's index (`'hd'` or `'turtle'`) to the decode worker as a container of its own.
///
/// Fire-and-forget in spirit but awaited in fact, because the boot prefetch that follows should go
/// through the worker rather than race it. A worker that refuses the layer is not an error here:
/// `packworker.js` keeps its corpus container and answers layer keys with a `miss`, which the page
/// already handles as "fetch it yourself".
async function openLayerInWorker(layer, base, index) {
  const worker = packs.worker;
  if (!worker || !index) return;
  const copy = index.slice().buffer;
  await new Promise((resolve) => {
    const done = (ok) => {
      clearTimeout(timer);
      worker.removeEventListener('message', onMessage);
      resolve(ok);
    };
    const onMessage = (e) => {
      const m = e.data;
      if (m && m.layer === layer && (m.type === 'opened' || m.type === 'failed')) {
        if (m.type === 'failed') {
          console.warn(`wenilla: pack worker would not open the ${layer} layer —`, m.error);
        }
        done(m.type === 'opened');
      }
    };
    const timer = setTimeout(() => done(false), WORKER_OPEN_TIMEOUT_MS);
    worker.addEventListener('message', onMessage);
    worker.postMessage({ type: 'open', layer, base, index: copy }, [copy]);
  });
}

/// Does the player want the updated character models? The `hdCharacterModels` CVar, read straight
/// out of `localStorage` because this runs long before the wasm module that owns CVars exists ―
/// with the `?hd_models=1` / `__wenilla_env` lever ahead of it, on `webenv::var`'s own ladder.
///
/// **A twin of `benilla_app::cvars::apply_boot_layers`, and it has to stay one.** If the page
/// fetched the layer and the client did not open it, the visitor pays 1.5 GiB for art they do not
/// see; if the client opened it and the page never warmed it, every character read is a cold round
/// trip. Both read the same key out of the same file and parse it the same lax way (`= "1"`,
/// `= "0"`, whitespace anywhere), so the failure mode of a mismatch is the one thing neither can
/// produce on its own.
///
/// Absent, unreadable, or unparseable all mean **on**, which is the registered default since
/// 2026-09-09 (`hdCharacterModels` is registered `"1"`; the options row is an opt-out). That flip
/// had to happen here in the same commit as the CVar: this function decides whether the PAGE
/// fetches `/data-hd`, and a page still defaulting to off against a client defaulting to on is
/// exactly the mismatch the paragraph above says neither side can produce alone — the client
/// would mount the layer and every character read would be a cold round trip.
function hdWanted() {
  return settingOn('hd_models', 'hdcharactermodels');
}

/// Does the player want the reforged art over the Turtle layer? The `reforgedModels` CVar (and
/// `?reforged_models=`), on `hdWanted`'s ladder; registered `"1"`, so absent means on. The twin of
/// `benilla_app::cvars::reforged_models_setting`.
function reforgedWanted() {
  return settingOn('reforged_models', 'reforgedmodels');
}

/// One boolean setting on `webenv::var`'s ladder: the page env object, then the query string,
/// then the saved CVar in `config.toml`, then the registered default — **on** for both readers.
function settingOn(envKey, cvar) {
  // The URL/env lever FIRST, exactly as `benilla_app::webenv::var` orders it: the page env object
  // (`window.__wenilla_env.hd_models`), then `?hd_models=1`, then the saved setting. The key is the
  // `$WOW_` prefix dropped and lowercased, which is that function's own rule for every switch it
  // serves. Without this arm the lever would move the client and not the page — the client would
  // mount a layer the page never fetched, and every character read would be a cold round trip.
  const env = window.__wenilla_env;
  if (env && env[envKey] !== undefined && env[envKey] !== null) {
    return layerSwitch(String(env[envKey])) === true;
  }
  const q = new URLSearchParams(location.search).get(envKey);
  if (q !== null) return layerSwitch(q) === true;

  let text = null;
  try {
    text = localStorage.getItem(CONFIG_KEY);
  } catch (_) {
    // A browser refusing site data has no saved setting to honour — and the client, reading the
    // same store through the same wall, falls to the same registered default.
    return true;
  }
  if (!text) return true; // never changed a setting: the default, which is on
  for (const line of text.split(/\r?\n/)) {
    const eq = line.indexOf('=');
    if (eq < 0) continue;
    if (line.slice(0, eq).trim().toLowerCase() !== cvar) continue;
    const raw = line
      .slice(eq + 1)
      .trim()
      .replace(/^"(.*)"$/, '$1');
    // An unparseable value is not an answer (`layerSwitch` answers null for an empty one), so it
    // falls through to the default rather than reading as off.
    return layerSwitch(raw) !== false;
  }
  return true; // a config file that never mentions the row is the default too
}

/// `benilla_formats::layers::layer_switch`, spelled for the page: `0`/`false`/`off` are off,
/// an empty value is no answer at all (`null`), anything else is on.
///
/// One rule, three readers (here, the client, and every `$WOW_HD_MODELS` tool), because the one
/// thing none of them can survive is disagreeing: a page that read `"0"` as truthy downloads
/// 1.5 GiB the client then refuses to mount.
function layerSwitch(raw) {
  const v = String(raw).trim();
  if (v === '') return null;
  return !(v === '0' || v === 'false' || v === 'off');
}

async function fetchIndex(base) {
  const r = await fetchRetry(`${base}/index.bpi`);
  if (!r.ok) throw new Error(`no container at ${base}/index.bpi (HTTP ${r.status})`);
  return new Uint8Array(await r.arrayBuffer());
}

